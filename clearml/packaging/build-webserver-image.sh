#!/usr/bin/env bash
# branding + nginx 를 clearml/server 이미지 안에 박아 넣는다.
# rehash 후 Dockerfile.webserver 의 COPY 목록도 갱신한다.
set -euo pipefail

CLEARML_DIR="${CLEARML_DIR:-/opt/clearml}"
BRANDING_DIR="${CLEARML_DIR}/branding"
MAP="${BRANDING_DIR}/rehash.map"
DOCKERFILE="${BRANDING_DIR}/Dockerfile.webserver"
TAG="${WEBSERVER_IMAGE:-clearml-webserver-intellivix:20260825}"
CONTEXT="${CLEARML_DIR}"

RED=$'\033[0;31m'; GRN=$'\033[0;32m'; BLU=$'\033[0;34m'; NC=$'\033[0m'
step() { echo -e "\n${BLU}▶ $*${NC}"; }
ok()   { echo -e "  ${GRN}✓${NC} $*"; }
die()  { echo -e "  ${RED}✗ $*${NC}" >&2; exit 1; }

docker info >/dev/null 2>&1 || die "docker 접근 불가 — sudo bash $0"

step "Dockerfile.webserver 생성 (rehash.map 반영)"
python3 - "$BRANDING_DIR" "$MAP" "$DOCKERFILE" <<'PY'
import os, sys
branding_dir, map_file, dockerfile = sys.argv[1:4]

pairs = []
for line in open(map_file, encoding="utf-8"):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    new, _, orig = line.partition("\t")
    if new and orig:
        pairs.append((new, orig))

def dest(orig: str) -> str:
    if orig.startswith("c-logomark-") and orig.endswith(".svg"):
        return f"/usr/share/nginx/html/media/{orig}"
    return f"/usr/share/nginx/html/{orig}"

static = [
    "index.html", "configuration.json", "favicon.ico",
    "logo.svg", "logo-white.svg", "small-logo.svg", "small-logo-white.svg",
    "c-logomark.svg",
]
static_dest = {
    "favicon.ico": ["/usr/share/nginx/html/favicon.ico",
                    "/usr/share/nginx/html/assets/favicon.ico"],
    "logo.svg": ["/usr/share/nginx/html/assets/logo.svg"],
    "logo-white.svg": ["/usr/share/nginx/html/assets/logo-white.svg"],
    "small-logo.svg": ["/usr/share/nginx/html/assets/small-logo.svg"],
    "small-logo-white.svg": ["/usr/share/nginx/html/assets/small-logo-white.svg"],
    "c-logomark.svg": ["/usr/share/nginx/html/app/webapp-common/assets/icons/c-logomark.svg"],
    "index.html": ["/usr/share/nginx/html/index.html"],
    "configuration.json": ["/usr/share/nginx/html/configuration.json"],
}

lines = [
    "# Intellivix branded ClearML webserver (generated by build-webserver-image.sh)",
    "FROM clearml/server:2.3.0-705",
    "",
    "COPY nginx/default.d/cache-control.conf /etc/nginx/default.d/cache-control.conf",
    "COPY nginx/default.d/index-no-store.conf /etc/nginx/default.d/index-no-store.conf",
    "COPY nginx/default.d/cache-bust.conf /etc/nginx/default.d/cache-bust.conf",
    "COPY nginx/default.d/data-studio.conf /etc/nginx/default.d/data-studio.conf",
    "",
]
for f in static:
    for d in static_dest[f]:
        lines.append(f"COPY branding/{f} {d}")

for new, orig in sorted(pairs, key=lambda x: x[1]):
    src = os.path.join(branding_dir, new)
    if not os.path.isfile(src):
        continue
    lines.append(f"COPY branding/{new} {dest(new)}")
    if new != orig:
        lines.append(f"COPY branding/{new} {dest(orig)}")

open(dockerfile, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"  wrote {dockerfile} ({len(lines)} lines)")
PY
ok "$DOCKERFILE"

step "docker build → ${TAG}"
docker build -f "$DOCKERFILE" -t "$TAG" "$CONTEXT"
ok "이미지 빌드 완료"

echo
echo "  다음: cd ${CLEARML_DIR} && docker compose -p clearml up -d --force-recreate webserver"
